def read_code(suite, task, partial=None):
    name = f's{suite}t{task}.cpp'
    if partial:
        p = ROOT / 'partial' / (partial if partial.endswith('.cpp') else partial + '.cpp')
    else:
        replacement = ROOT / 'new_std' / name
        p = replacement if replacement.exists() else ROOT / f'source{suite}' / f'T{task}' / 'judge/std.cpp'
    s = p.read_text(encoding='utf-8').replace('\r\n','\n').strip() + '\n'
    if p.parent.name not in ['new_std','partial']:
        s = s.replace('#include <bits/stdc++.h>','#include<bits/stdc++.h>')
        s = s.replace('cin.tie(0);','cin.tie(nullptr);')
        lines = []
        for line in s.splitlines():
            lead = len(line) - len(line.lstrip(' '))
            if lead and lead % 4 == 0:
                line = '\t' * (lead // 4) + line[lead:]
            line = re.sub(r'\b(for|if|while) \(',r'\1(',line)
            if not line.lstrip().startswith('//'):
                line = line.replace(') {','){').replace('} else {','}else{')
            lines.append(line)
        s = '\n'.join(lines).strip() + '\n'
    return s

