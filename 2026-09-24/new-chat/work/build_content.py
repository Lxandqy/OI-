PARTIAL_SOURCE = {(6,3):'source6/T3/judge/some.cpp',(6,4):'source6/T4/judge/some.cpp',(7,2):'source7/T2/judge/some.cpp',(7,4):'source7/T4/judge/some.cpp'}

def code_for_partial(suite,task,name):
    if (suite,task) in PARTIAL_SOURCE and name == f's{suite}t{task}':
        s=(ROOT/PARTIAL_SOURCE[suite,task]).read_text(encoding='utf-8')
        s=s.replace('#include <bits/stdc++.h>','#include<bits/stdc++.h>').replace('cin.tie(0);','cin.tie(nullptr);')
        lines=[]
        for line in s.splitlines():
            lead=len(line)-len(line.lstrip(' '))
            if lead and lead%4==0: line='\t'*(lead//4)+line[lead:]
            line=re.sub(r'\b(for|if|while) \(',r'\1(',line)
            if not line.lstrip().startswith('//'): line=line.replace(') {','){').replace('} else {','}else{')
            lines.append(line)
        return '\n'.join(lines).strip()+'\n'
    return read_code(suite,task,name)

def section(title,body):
    return f'## {title}\n\n---\n\n{body.strip()}\n\n'

def solution(suite,task):
    p=P[suite,task]
    out=f'# T{task} {p["title"]}\n\n---\n\n'
    out+=section('题意简化',p['intro'])
    out+=section('问题拆分',p['split'])
    for item in p['partials']:
        title,body=item[:2]
        if len(item)>2:
            body+='\n\n'+fence(code_for_partial(suite,task,item[2]))
        out+=section(title,body)
    title,body=p['full']
    if 'diagram' in p:
        body+='\n\n'+DIAGRAMS[p['diagram']]
    body+='\n\n'+fence(read_code(suite,task))
    out+=section(title,body)
    out+=section('知识点总结',p['conclusion'])
    return format_solution(out.rstrip()+'\n')

def zip_files(files,path):
    with zipfile.ZipFile(path,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=6) as z:
        for p in files:
            z.write(p,p.name)

